#!/usr/bin/env python3
"""Generate the 25-tap symmetric low-pass coefficients for blocks/fir_decim2.
Writes rtl/fir_coefs_pkg.sv (Q1.17 signed 18-bit, DSP48E2 B-port) and tb/fir_coefs.py (same ints).
Usage: python tools/gen_fir_coefs.py [blocks/fir_decim2]"""
import sys, pathlib
import numpy as np
from scipy.signal import firwin

NTAPS, COEF_W, FRAC = 25, 18, 17
h = firwin(NTAPS, 0.4, window="hamming")          # cutoff = 0.2 fs; 0.5 would be half-band (even taps zero) and hide the symmetry story
q = np.round(h * (1 << FRAC)).astype(int)
assert np.array_equal(q, q[::-1]), "coefficients must be symmetric"
assert abs(q).max() < (1 << (COEF_W - 1)), "coefficient overflow"

blk = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "blocks/fir_decim2")
sv = ["// Generated by tools/gen_fir_coefs.py — do not edit. scipy.signal.firwin(25, 0.4, window='hamming'), Q1.17",
      "package fir_coefs_pkg;",
      f"  localparam int unsigned NTAPS  = {NTAPS};",
      f"  localparam int unsigned COEF_W = {COEF_W};",
      "  // Flat vector (Yosys rejects array localparams in packages): h[i] = COEF_FLAT[i*COEF_W +: COEF_W].",
      "  // Listed h[24] first ... h[0] last so that h[0] occupies the LSBs.",
      "  localparam logic [NTAPS*COEF_W-1:0] COEF_FLAT = {"]
sv += [f"    {COEF_W}'sd{c},  // h[{i}]" if c >= 0 else f"    -{COEF_W}'sd{-c},  // h[{i}]" for i, c in reversed(list(enumerate(q)))]
sv[-1] = sv[-1].replace(",  //", "   //")
sv += ["  };", "endpackage"]
(blk / "rtl" / "fir_coefs_pkg.sv").write_text("\n".join(sv) + "\n")
(blk / "tb" / "fir_coefs.py").write_text("# Generated by tools/gen_fir_coefs.py — do not edit\n"
                                         f"COEF = {q.tolist()}\nFRAC = {FRAC}\n")
print(f"wrote {NTAPS} coefficients, sum={q.sum()} (DC gain {q.sum()/(1<<FRAC):.4f}), max={abs(q).max()}")
