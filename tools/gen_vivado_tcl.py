#!/usr/bin/env python3
"""Emit the customer-side Vivado hand-off for a block: synth/vivado_synth.tcl + synth/constraints.xdc.

Called by `make synth` (mk/block.mk). Existing files are left untouched so a hand-tuned
script (e.g. blocks/fir_decim2) is never overwritten; delete them to regenerate.
Nothing here runs Vivado — it only writes the script the customer runs on a licensed machine.
"""
import argparse
import pathlib
import sys

TCL = """\
# Customer-side sign-off synthesis for {top} (run on a licensed Vivado):
#   cd {block}/synth && vivado -mode batch -source vivado_synth.tcl [-tclargs <part>]
# Generated by tools/gen_vivado_tcl.py from the block Makefile (TOP/SRCS/CLK_MHZ/PART);
# gives what Yosys cannot: exact primitive counts and timing (WNS) at {mhz} MHz.
set part {part}
if {{$argc > 0}} {{ set part [lindex $argv 0] }}
{reads}
read_xdc constraints.xdc
synth_design -top {top} -part $part -mode out_of_context -retiming
report_utilization    -file utilization.rpt
report_timing_summary -file timing_summary.rpt
puts "DONE: see utilization.rpt (LUT/FF/DSP48E2/BRAM rows) and timing_summary.rpt (WNS >= 0 means {mhz} MHz met)"
"""

XDC = """\
create_clock -period {period:.3f} -name {clk} [get_ports {clk}]   ;# {mhz} MHz target
set_input_delay  -clock {clk} 0.5 [remove_from_collection [all_inputs] [get_ports {clk}]]
set_output_delay -clock {clk} 0.5 [all_outputs]
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--block", required=True, help="block dir (abs or repo-relative), for the comment")
    ap.add_argument("--top", required=True)
    ap.add_argument("--srcs", nargs="+", required=True, help="RTL sources relative to the block dir")
    ap.add_argument("--clk", default="clk", help="clock port name")
    ap.add_argument("--mhz", type=float, default=300.0)
    ap.add_argument("--part", default="xczu28dr-ffvg1517-2-e", help="default FPGA part (ZCU111 RFSoC)")
    ap.add_argument("--out", default="synth")
    a = ap.parse_args()

    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tcl, xdc = out / "vivado_synth.tcl", out / "constraints.xdc"
    mhz = int(a.mhz) if a.mhz == int(a.mhz) else a.mhz
    wrote = []
    if not tcl.exists():
        reads = "\n".join(f"read_verilog -sv ../{s}" for s in a.srcs)
        tcl.write_text(TCL.format(top=a.top, block=a.block, part=a.part, mhz=mhz, reads=reads))
        wrote.append(tcl)
    if not xdc.exists():
        xdc.write_text(XDC.format(clk=a.clk, mhz=mhz, period=1000.0 / a.mhz))
        wrote.append(xdc)
    if wrote:
        print("vivado hand-off written: " + ", ".join(str(p) for p in wrote) + f"  (run: cd {a.out} && vivado -mode batch -source vivado_synth.tcl)")
    else:
        print(f"vivado hand-off already present: {tcl}, {xdc} (delete to regenerate)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
